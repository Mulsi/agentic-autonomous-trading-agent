import { sql } from 'drizzle-orm';
import { boolean, check, pgTable, timestamp, uuid } from 'drizzle-orm/pg-core';

// Trading tables arrive with the milestone that first uses them (SLICE_1_PLAN
// §7). This file holds only the database identity marker (src/db/identity.ts).
//
// Column conventions, enforced by test/unit/db/schema-scan.spec.ts:
// - money is `numeric` in its default string mode, never `real`,
//   `doublePrecision`, or `numeric` in number or bigint mode
// - time is `timestamp` with `withTimezone: true`, or epoch milliseconds in a
//   number-mode `bigint` whose SQL name ends in `_ms`
// - no `customType`

/**
 * One row per database, generated by Postgres with `gen_random_uuid()` in a
 * migration. The app reads it and never writes it. `singleton` is the primary
 * key and must be true, so the table holds at most one row.
 */
export const databaseIdentity = pgTable(
  'database_identity',
  {
    singleton: boolean('singleton').primaryKey().default(true),
    marker: uuid('marker').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [check('database_identity_singleton', sql`${table.singleton}`)],
);
